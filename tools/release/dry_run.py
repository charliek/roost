#!/usr/bin/env python3
"""Generate a publish-free copy of .github/workflows/release.yml.

The output builds every release artifact (linux amd64/arm64, mac, mac-iced)
on a `dryrun/**` branch push and uploads them as workflow artifacts. It
publishes nothing: no draft release, no Sparkle signing, no appcast, no apt
dispatch, no notarization. See tools/release/README.md.

The transform is textual on purpose. A YAML round-trip would read `on:` as
True, reformat every `run:` block, and need PyYAML. Every edit asserts that
the text it expects is there, so a release.yml change this tool doesn't
understand fails the run instead of silently producing a different workflow.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
SOURCE = REPO_ROOT / ".github" / "workflows" / "release.yml"
CARGO_TOML = REPO_ROOT / "Cargo.toml"
DEFAULT_OUT = REPO_ROOT / ".github" / "workflows" / "release-dryrun.yml"

REMOVED_JOBS = (
    "ci-gate",
    "create-release",
    "publish-release",
    "appcast",
    "appcast-iced",
    "dispatch-apt-charliek",
)
KEPT_JOBS = ("version-check", "linux", "mac", "mac-iced")
BUILD_JOBS = ("linux", "mac", "mac-iced")
NOTARIZING_JOBS = ("mac", "mac-iced")

DELETED_STEPS = {
    "mac": (
        "Sign the DMG for Sparkle",
        "Hand sign.txt to the appcast job",
        "Append macOS first-launch note to release body",
    ),
    "mac-iced": (
        "Sign the DMG for Sparkle",
        "Hand sign-iced.txt to the appcast-iced job",
    ),
}

JOB_KEY = re.compile(r"^  ([A-Za-z0-9_-]+):\s*$")
STEP_START = re.compile(r"^      - ")
STEP_NAME = re.compile(r"^      - name: (.+?)\s*$")
CAN_NOTARIZE = re.compile(r"^      CAN_NOTARIZE: .*$")
SECRET_REF = re.compile(r"\bsecrets\b(?!\.GITHUB_TOKEN\b)")
IDENTITY_EXPR = re.compile(
    r"\$\{\{ env\.CAN_NOTARIZE == 'true' && secrets\.ROOST_DEVELOPER_ID_IDENTITY \|\| '' \}\}"
)
TAG_CONDITION = re.compile(
    r"^\s+(?:- )?if:.*(?:github\.ref|refs/tags|ref_name|startsWith\()", re.M
)
STEP_REF = re.compile(r"\bsteps\.([A-Za-z0-9_-]+)\.")
STEP_ID = re.compile(r"^        id: (\S+)\s*$", re.M)

HEADER = """\
name: Release dry run

# GENERATED by tools/release/dry_run.py from .github/workflows/release.yml.
# Do not edit. Never committed to a long-lived branch: it lives only on a
# throwaway dryrun/** branch (tools/release/README.md).
#
# Builds every release artifact and publishes nothing.

on:
  push:
    branches:
      - 'dryrun/**'

permissions:
  contents: read

env:
  DRYRUN_TAG: {tag}

"""

GH_SHIM_STEP = """\
      - name: Install the dry-run gh shim
        shell: bash
        run: |
          set -euo pipefail
          shim_dir="${RUNNER_TEMP}/dryrun-bin"
          mkdir -p "${shim_dir}" "${RUNNER_TEMP}/dryrun"
          cat > "${shim_dir}/gh" <<'SHIM'
          #!/usr/bin/env bash
          set -euo pipefail
          out="${RUNNER_TEMP}/dryrun"
          if [ "${1:-}" = release ]; then
            case "${2:-}" in
              upload)
                shift 2
                tag_seen=0
                for arg in "$@"; do
                  case "${arg}" in --*) continue ;; esac
                  if [ "${tag_seen}" = 0 ]; then tag_seen=1; continue; fi
                  file="${arg%%#*}"
                  if [ ! -f "${file}" ]; then
                    echo "::error::dry-run gh shim: ${file} does not exist"
                    exit 1
                  fi
                  dest="${out}/$(basename "${file}")"
                  if [ -e "${dest}" ]; then
                    echo "::error::dry-run gh shim: ${dest} is already staged"
                    exit 1
                  fi
                  mkdir -p "${out}"
                  cp "${file}" "${dest}"
                  echo "dry-run gh shim: staged ${file}"
                done
                exit 0
                ;;
              view|edit)
                echo "::error::dry-run gh shim: 'gh release $2' must not run in a dry run"
                exit 1
                ;;
            esac
          fi
          shim_dir="$(cd "$(dirname "$0")" && pwd)"
          real_gh="$(PATH="${PATH//${shim_dir}:/}" command -v gh || true)"
          if [ -z "${real_gh}" ]; then
            echo "::error::dry-run gh shim: no real gh on PATH to pass '$*' to"
            exit 1
          fi
          exec "${real_gh}" "$@"
          SHIM
          chmod +x "${shim_dir}/gh"
          echo "${shim_dir}" >> "${GITHUB_PATH}"

"""

UPLOAD_STEP = """\
      - name: Collect the dry-run artifacts
        uses: actions/upload-artifact@v7
        with:
          name: {name}
          path: ${{{{ runner.temp }}}}/dryrun/
          retention-days: 1
          if-no-files-found: error
"""


class Unexpected(SystemExit):
    def __init__(self, message: str):
        super().__init__(f"dry_run.py: release.yml changed shape: {message}")


def workspace_version(cargo_text: str) -> str:
    m = re.search(r"^\[workspace\.package\]\s*$", cargo_text, re.M)
    if not m:
        raise SystemExit("dry_run.py: Cargo.toml has no [workspace.package] table")
    rest = cargo_text[m.end():]
    nxt = re.search(r"^\[", rest, re.M)
    section = rest[: nxt.start()] if nxt else rest
    v = re.search(r'^version\s*=\s*"([^"]+)"', section, re.M)
    if not v:
        raise SystemExit("dry_run.py: [workspace.package] has no version")
    return v.group(1)


def split_jobs(lines: list[str]) -> tuple[list[str], list[tuple[str, list[str]]]]:
    """(lines before `jobs:` inclusive, [(job id, its lines)]).

    A job owns the comment lines directly above its key, so removing a job
    removes the prose written about it.
    """
    try:
        jobs_at = lines.index("jobs:\n")
    except ValueError:
        raise Unexpected("no top-level `jobs:`") from None
    head = lines[: jobs_at + 1]
    body = lines[jobs_at + 1 :]
    starts = [i for i, ln in enumerate(body) if JOB_KEY.match(ln)]
    if not starts:
        raise Unexpected("`jobs:` has no jobs")
    owned = []
    for s in starts:
        c = s
        while c > 0 and body[c - 1].startswith("  #"):
            c -= 1
        owned.append(c)
    # Lines before the first job's comment block (e.g. a leading comment
    # that explains the whole `jobs:` section) stay with the header.
    head += body[: owned[0]]
    jobs = []
    for n, s in enumerate(starts):
        end = owned[n + 1] if n + 1 < len(starts) else len(body)
        jobs.append((JOB_KEY.match(body[s]).group(1), body[owned[n] : end]))
    return head, jobs


def split_steps(job: list[str], job_id: str) -> tuple[list[str], list[list[str]]]:
    try:
        steps_at = job.index("    steps:\n")
    except ValueError:
        raise Unexpected(f"job {job_id} has no `    steps:`") from None
    pre = job[: steps_at + 1]
    body = job[steps_at + 1 :]
    for ln in body:
        if ln.strip() and not ln.startswith("      ") and not ln.startswith("  #"):
            if re.match(r"^    [A-Za-z]", ln):
                raise Unexpected(f"job {job_id}: a key follows `steps:`")
    starts = [i for i, ln in enumerate(body) if STEP_START.match(ln)]
    if not starts:
        raise Unexpected(f"job {job_id} has no steps")
    owned = []
    for s in starts:
        c = s
        while c > 0 and body[c - 1].startswith("      #"):
            c -= 1
        owned.append(c)
    pre += body[: owned[0]]
    steps = []
    for n in range(len(starts)):
        end = owned[n + 1] if n + 1 < len(starts) else len(body)
        steps.append(body[owned[n] : end])
    return pre, steps


def code_lines(text: str) -> str:
    return "".join(
        ln for ln in text.splitlines(keepends=True) if not ln.lstrip().startswith("#")
    )


def step_name(step: list[str]) -> str | None:
    for ln in step:
        m = STEP_NAME.match(ln)
        if m:
            return m.group(1).strip("'\"")
        if STEP_START.match(ln):
            break
    return None


def rewrite_ref_name(text: str) -> str:
    text = re.sub(r"\$\{GITHUB_REF_NAME", "${DRYRUN_TAG", text)
    text = re.sub(r"\$GITHUB_REF_NAME\b", "$DRYRUN_TAG", text)
    text = text.replace("github.ref_name", "env.DRYRUN_TAG")
    return text


def rewrite_permissions(job: list[str], job_id: str) -> list[str]:
    try:
        at = job.index("    permissions:\n")
    except ValueError:
        raise Unexpected(f"job {job_id} has no `permissions:` block") from None
    end = at + 1
    while end < len(job) and job[end].startswith("      ") and job[end].strip():
        end += 1
    if end == at + 1:
        raise Unexpected(f"job {job_id}: empty permissions block")
    return job[: at + 1] + ["      contents: read\n"] + job[end:]


def transform(source: str, version: str) -> str:
    lines = source.splitlines(keepends=True)
    if not lines or not lines[-1].endswith("\n"):
        raise Unexpected("source does not end in a newline")
    head, jobs = split_jobs(lines)

    ids = [j for j, _ in jobs]
    for want in REMOVED_JOBS + KEPT_JOBS:
        if want not in ids:
            raise Unexpected(f"job {want!r} not found (have {ids})")
    unknown = [j for j in ids if j not in REMOVED_JOBS + KEPT_JOBS]
    if unknown:
        raise Unexpected(
            f"jobs {unknown} are new; decide whether the dry run keeps or removes them"
        )

    head_text = "".join(head)
    perms = head_text.find("\npermissions:\n  contents: read\n")
    if perms < 0:
        raise Unexpected("top-level `permissions: contents: read` not found")
    conc = head_text.find("\nconcurrency:\n")
    jobs_at = head_text.rfind("\njobs:\n")
    if not 0 <= perms < conc < jobs_at:
        raise Unexpected("expected permissions, concurrency, jobs in that order")
    tail = head_text[conc + 1 :]
    out = [HEADER.format(tag=f"v{version}"), tail]

    for job_id, job in jobs:
        if job_id not in KEPT_JOBS:
            continue
        text = "".join(job)
        if TAG_CONDITION.search(text):
            raise Unexpected(
                f"job {job_id} has an `if:` on the ref or a tag; on a dryrun/** branch"
                " it would skip the job and the run could finish green"
            )
        if job_id in NOTARIZING_JOBS:
            text, n = IDENTITY_EXPR.subn("''", text)
            if n == 0:
                raise Unexpected(f"job {job_id}: no ROOST_DEVELOPER_ID_IDENTITY expression")
        if job_id in BUILD_JOBS:
            if "    needs: create-release\n" not in text:
                raise Unexpected(f"job {job_id} lost `needs: create-release`")
            text = text.replace(
                "    needs: create-release\n", "    needs: version-check\n", 1
            )
            job = rewrite_permissions(text.splitlines(keepends=True), job_id)
        else:
            job = text.splitlines(keepends=True)

        if job_id in NOTARIZING_JOBS:
            hits = [i for i, ln in enumerate(job) if CAN_NOTARIZE.match(ln)]
            if len(hits) != 1:
                raise Unexpected(f"job {job_id}: expected one CAN_NOTARIZE, found {len(hits)}")
            job[hits[0]] = "      CAN_NOTARIZE: 'false'\n"

        pre, steps = split_steps(job, job_id)
        wanted = list(DELETED_STEPS.get(job_id, ()))
        kept = []
        dropped_ids = set()
        for step in steps:
            name = step_name(step)
            if name in wanted:
                wanted.remove(name)
            elif not SECRET_REF.search(code_lines("".join(step))):
                kept.append(step)
                continue
            dropped_ids.update(STEP_ID.findall("".join(step)))
        if wanted:
            raise Unexpected(f"job {job_id}: steps {wanted} not found")
        for step in kept:
            for ref in STEP_REF.findall(code_lines("".join(step))):
                if ref in dropped_ids:
                    raise Unexpected(
                        f"job {job_id}: step {step_name(step)!r} reads the output of"
                        f" the deleted step {ref!r}"
                    )

        job_out = "".join(pre)
        if job_id in BUILD_JOBS:
            job_out += GH_SHIM_STEP
        body = "".join("".join(s) for s in kept).rstrip("\n") + "\n"
        job_out += body

        if job_id in BUILD_JOBS:
            if "    strategy:\n" in job_out:
                if "matrix.arch" not in job_out:
                    raise Unexpected(f"job {job_id}: matrix has no `arch` to name artifacts by")
                name = f"dryrun-{job_id}-${{{{ matrix.arch }}}}"
            else:
                if "runs-on: macos-26" not in job_out:
                    raise Unexpected(f"job {job_id}: not a macos-26 (arm64) job")
                name = f"dryrun-{job_id}-arm64"
            job_out += "\n" + UPLOAD_STEP.format(name=name)

        out.append(rewrite_ref_name(job_out).rstrip("\n") + "\n\n")

    result = "".join(out).rstrip("\n") + "\n"
    left = SECRET_REF.search(code_lines(result))
    if left:
        line = code_lines(result)[: left.start()].count("\n") + 1
        raise Unexpected(f"a production secret reference survived (output line ~{line})")
    for needle in ("GITHUB_REF_NAME", "github.ref_name"):
        if needle in result:
            raise Unexpected(f"{needle} survived the rewrite")
    return result


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--src", type=Path, default=SOURCE)
    ap.add_argument("--cargo", type=Path, default=CARGO_TOML)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args(argv)
    version = workspace_version(args.cargo.read_text())
    args.out.write_text(transform(args.src.read_text(), version))
    print(f"wrote {args.out} (DRYRUN_TAG=v{version})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
